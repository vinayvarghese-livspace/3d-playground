# Converts a Shot List CSV into data.js (same shape as convert-naming-data.ps1).
param(
  [Parameter(Mandatory = $true)][string]$Source,
  [string]$Out = (Join-Path $PSScriptRoot '..\data.js'),
  [string]$SourceLabel
)
$ErrorActionPreference = 'Stop'

$file = Get-Item -LiteralPath $Source
if (-not $SourceLabel) { $SourceLabel = $file.Name }
Write-Host "Source: $($file.FullName)"

$oldNames = @()
if (Test-Path -LiteralPath $Out) {
  $oldJs = Get-Content -LiteralPath $Out -Raw
  $oldNames = @(
    [regex]::Matches($oldJs, 'name: "([^"]+)",\r?\n\s+category:') |
      ForEach-Object { $_.Groups[1].Value }
  )
}

$rows = Import-Csv -LiteralPath $file.FullName
$warnings = New-Object System.Collections.Generic.List[string]
$types = [ordered]@{}
$current = $null
$currentVariant = ''
$category = ''

foreach ($r in $rows) {
  $cat = ("$($r.Category)").Trim()
  $typeName = ("$($r.'Product Type')").Trim()
  $variant = ("$($r.Variant)").Trim()
  $seq = ("$($r.Seq)").Trim()
  $name = ("$($r.'Image Name')").Trim()
  $code = ("$($r.'Shot Code')").Trim()

  if (-not ($cat -or $typeName -or $variant -or $seq -or $name -or $code)) { continue }

  if ($typeName) {
    if ($cat) { $category = $cat }
    elseif (-not $category) { $warnings.Add("Product type '$typeName' has no category") }
    $currentVariant = $variant
    $key = "$category`t$typeName"
    if (-not $types.Contains($key)) {
      $types[$key] = [ordered]@{ name = $typeName; category = $category; blocks = [ordered]@{} }
    }
    $t = $types[$key]
    if ($t.blocks.Contains($variant)) {
      $label = if ($variant) { "$variant (dup)" } else { 'Standard (dup)' }
      $vLabel = if ($variant) { $variant } else { '(no variant)' }
      $warnings.Add("'$typeName' / '$vLabel' already exists - using '$label'")
      $variant = $label
    }
    $t.blocks[$variant] = New-Object System.Collections.Generic.List[object]
    $current = $t.blocks[$variant]
  } elseif ($cat) {
    $warnings.Add("category set without product type - ignored: $cat")
  }

  if ($null -eq $current) {
    $warnings.Add('shot before any product type - skipped')
    continue
  }
  if (-not $name -or -not $code -or -not $seq) {
    $warnings.Add('missing Seq/Image Name/Shot Code - skipped')
    continue
  }
  if ($seq -match '^\d+$') { $seq = $seq.PadLeft(2, '0') }

  $note = ''
  if ($name -match '^(.*?)\s*\((Marketplace MAIN)\)\s*$') {
    $name = $matches[1]
    $note = $matches[2]
  }

  $current.Add([ordered]@{ seq = $seq; name = $name; code = $code; note = $note })
}

function JsStr($s) {
  $s = "$s" -replace '\\', '\\' -replace '"', '\"'
  return '"' + $s + '"'
}
function ShotsJs($shots, $indent) {
  $items = foreach ($s in $shots) {
    $parts = @("seq: $(JsStr $s.seq)", "name: $(JsStr $s.name)", "code: $(JsStr $s.code)")
    if ($s.note) { $parts += "note: $(JsStr $s.note)" }
    "$indent  { " + ($parts -join ', ') + ' }'
  }
  return "[`n" + ($items -join ",`n") + "`n$indent]"
}

$typeJs = foreach ($t in $types.Values) {
  $keys = @($t.blocks.Keys)
  $named = @($keys | Where-Object { $_ })
  $head = "    {`n      name: $(JsStr $t.name),`n      category: $(JsStr $t.category),`n"
  if ($named.Count) {
    $vs = foreach ($k in $keys) {
      $label = if ($k) { $k } else { 'Standard' }
      "        $(JsStr $label): $(ShotsJs $t.blocks[$k] '        ')"
    }
    $head + "      variants: {`n" + ($vs -join ",`n") + "`n      }`n    }"
  } else {
    $head + "      shots: $(ShotsJs $t.blocks[''] '      ')`n    }"
  }
}

$updated = $file.LastWriteTime.ToString('yyyy-MM-ddTHH:mm:ss')
$js = @"
// Generated by tools/convert-naming-data.ps1 - do not edit by hand.
// Source: $SourceLabel
window.NAMING_DATA = {
  source: $(JsStr $SourceLabel),
  updatedAt: $(JsStr $updated),
  minSize: 3000,
  outputSize: 3000,
  productTypes: [
$($typeJs -join ",`n")
  ]
};
"@

$outPath = [IO.Path]::GetFullPath($Out)
[IO.File]::WriteAllText($outPath, $js, (New-Object Text.UTF8Encoding($false)))

$newNames = @($types.Values | ForEach-Object { $_.name })
$added = @($newNames | Where-Object { $oldNames -notcontains $_ })
$removed = @($oldNames | Where-Object { $newNames -notcontains $_ })
$shotCount = ($types.Values | ForEach-Object { $_.blocks.Values | ForEach-Object { $_.Count } } | Measure-Object -Sum).Sum
$withVariants = @($types.Values | Where-Object { @($_.blocks.Keys | Where-Object { $_ }).Count -gt 0 }).Count

Write-Host "Product types: $($types.Count)  Shots: $shotCount  With variants: $withVariants"
Write-Host "Old types: $($oldNames.Count)  New types: $($newNames.Count)"
Write-Host "ADDED ($($added.Count)):"
foreach ($n in $added) {
  $t = $types.Values | Where-Object { $_.name -eq $n } | Select-Object -First 1
  $blocks = $t.blocks
  $keys = @($blocks.Keys)
  $shotN = ($blocks.Values | ForEach-Object { $_.Count } | Measure-Object -Sum).Sum
  $namedKeys = @($keys | Where-Object { $_ })
  $varInfo = if ($namedKeys.Count) {
    'variants: ' + (($keys | ForEach-Object { if ($_) { $_ } else { 'Standard' } }) -join '; ')
  } else {
    'no variants'
  }
  Write-Host "  - $($t.category) / $($t.name) ($shotN shots, $varInfo)"
  foreach ($k in $keys) {
    $label = if ($k) { $k } else { '(shots)' }
    $codes = ($blocks[$k] | ForEach-Object { "$($_.seq):$($_.code)" }) -join ', '
    Write-Host "      [$label] $codes"
  }
}
Write-Host "REMOVED ($($removed.Count)):"
$removed | ForEach-Object { Write-Host "  - $_" }

if ($warnings.Count) {
  Write-Host "Warnings ($($warnings.Count)):"
  $warnings | Select-Object -First 30 | ForEach-Object { Write-Host "  $_" }
} else {
  Write-Host 'No warnings.'
}
Write-Host "Wrote: $outPath"
